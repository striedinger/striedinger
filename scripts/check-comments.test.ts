import { describe, expect, it } from "vitest";

import { disallowedComments, removeComments } from "./check-comments.mts";

function flagged(path: string, source: string) {
  return disallowedComments(path, source).map(function commentText(comment) {
    return comment.text;
  });
}

function fixed(path: string, source: string) {
  return removeComments(source, disallowedComments(path, source));
}

describe("comment checker", function () {
  it("ignores comment markers inside TypeScript strings, templates, and regular expressions", function () {
    const source = [
      'const url = "https://example.com"; // trailing',
      "const pattern = /\\/\\/not-a-comment/;",
      "const template = `/* still text */`;",
    ].join("\n");
    expect(flagged("page.ts", source)).toEqual(["// trailing"]);
  });

  it("allows TSDoc, lint directives with reasons, and triple-slash references", function () {
    const source = [
      '/// <reference lib="webworker" />',
      "/** Formats a price. */",
      "export function format() {",
      "  // oxlint-disable-next-line no-console -- Reports the failure",
      "  console.log(1);",
      "}",
    ].join("\n");
    expect(flagged("format.ts", source)).toEqual([]);
  });

  it("removes a JSX comment together with its braces", function () {
    const source = ["<div>", "  {/* Heading */}", "  <h1 />", "</div>", ""].join("\n");
    expect(fixed("view.tsx", source)).toBe(["<div>", "  <h1 />", "</div>", ""].join("\n"));
  });

  it("keeps Rust doc comments and SAFETY notes but flags ordinary ones", function () {
    const source = [
      "//! Crate docs.",
      "/// Item docs.",
      "fn f<'a>(s: &'a str) -> char {",
      '    let raw = r#"// not a comment"#;',
      "    // SAFETY: the pointer is valid for the call.",
      "    let quote = '\"'; // plain",
      "    'x'",
      "}",
    ].join("\n");
    expect(flagged("lib.rs", source)).toEqual(["// plain"]);
  });

  it("finds Swift comments outside strings and interpolations", function () {
    const source = [
      "// swift-tools-version:5.9",
      'let label = "\\(count > 1 ? "a // b" : "c")" // plain',
      "/// Docs.",
    ].join("\n");
    expect(flagged("App.swift", source)).toEqual(["// plain"]);
  });

  it("keeps workflow action version tags and shebangs but removes other hash comments", function () {
    const source = [
      "steps:",
      "  # Explains the step.",
      "  - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1",
      "  - run: echo \"#not-a-comment\" '# also text' # trailing",
      "",
    ].join("\n");
    expect(fixed("ci.yml", source)).toBe(
      [
        "steps:",
        "  - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1",
        "  - run: echo \"#not-a-comment\" '# also text'",
        "",
      ].join("\n"),
    );
    expect(flagged("run.sh", "#!/usr/bin/env bash\necho ${#items}\n")).toEqual([]);
  });

  it("leaves shell heredoc bodies alone", function () {
    const source = ["cat > out.cmake <<EOF", "# part of the generated file", "EOF", ""].join("\n");
    expect(flagged("build.sh", source)).toEqual([]);
  });

  it("does not leave doubled blank lines where a comment line was removed", function () {
    const source = ["a = 1", "", "# note", "", "b = 2", ""].join("\n");
    expect(fixed("config.toml", source)).toBe(["a = 1", "", "b = 2", ""].join("\n"));
  });

  it("skips vendored and generated files", function () {
    expect(flagged("next-env.d.ts", "// generated by Next.js\n")).toEqual([]);
    expect(flagged(".agents/skill/run.sh", "# vendored\n")).toEqual([]);
  });
});
